"""Identity report: how records were matched, how well, and what is still open -> reports/identity_report.md

    python -m trustissues.factory.identity.evaluate

There are no identity labels in the release. The independent check is the collections data: every case lists
the card / loan / deposit accounts it covers under a CRM ID. That link is never used for matching, so it measures
the matcher. The case data has its own errors (CRM IDs one character off), which the report separates out.
All numbers are generated from the warehouse.
"""
from __future__ import annotations

from trustissues.common import config
from trustissues.common.db import connect

REPORT = config.REPO_ROOT / "reports" / "identity_report.md"

EVIDENCE_SQL = """
CREATE OR REPLACE TEMP TABLE case_evidence AS
WITH ca AS (SELECT coll_customer_ref crm, trim(unnest(CASE WHEN account_ids LIKE '[%' THEN from_json(account_ids, '["VARCHAR"]')
                                                     ELSE string_split(account_ids, ';') END)) acct
            FROM curated.collections_cases)
SELECT DISTINCT a.golden_customer_id AS acct_golden, a.source_system || '|' || a.source_key AS acct_node,
       ca.crm AS case_crm, xc.golden_customer_id AS case_golden
FROM ca JOIN gold.c360_account a ON a.account_id = ca.acct
LEFT JOIN gold.customer_xref xc ON xc.node_id = 'crm|' || ca.crm
"""


def table(rows, headers) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join(f"{v:,}" if isinstance(v, int) else (f"{v:.4f}" if isinstance(v, float) else str(v)) for v in r) + " |")
    return "\n".join(out)


def build(con) -> str:
    q = lambda sql: con.execute(sql).fetchall()
    one = lambda sql: con.execute(sql).fetchone()
    s = config.settings()["identity"]
    md = ["# Identity resolution report", "",
          "Generated by `python -m trustissues.factory.identity.evaluate` from the warehouse. Do not edit by hand.", ""]

    people, records = one("SELECT count(DISTINCT golden_customer_id), count(*) FROM gold.customer_xref")
    crm_people = one("SELECT count(DISTINCT golden_customer_id) FROM gold.customer_xref WHERE source_system = 'crm'")[0]
    md += ["## 1. Outcome", "",
           f"{records:,} source customers resolved to **{people:,} people** ({crm_people:,} of them have a CRM record). "
           "The release says the bank has 1,000,000 customers.", ""]
    md += [table(q("""SELECT source_system, count(*), count(*) FILTER (WHERE status = 'linked'),
                        count(*) FILTER (WHERE status = 'singleton'), count(*) FILTER (WHERE status = 'in_review'),
                        count(*) FILTER (WHERE status = 'blocked_conflict'), count(*) FILTER (WHERE status = 'unresolved')
                      FROM gold.customer_xref GROUP BY 1 ORDER BY 1"""),
                 ["source", "records", "linked", "singleton", "in review", "blocked conflict", "unresolved"]), ""]
    md += ["Linked non-CRM records with no CRM record in their cluster are linked only to each other (for example a "
           "deposit CIF and its bureau file).", ""]
    md += [table(q("""SELECT source_system, count(*) FROM gold.customer_xref x WHERE status = 'linked' AND source_system <> 'crm'
                      AND NOT EXISTS (SELECT 1 FROM gold.customer_xref c WHERE c.golden_customer_id = x.golden_customer_id
                                      AND c.source_system = 'crm') GROUP BY 1 ORDER BY 1"""),
                 ["source", "linked, but no CRM record in the cluster"]), ""]

    md += ["## 2. How each record was attached", "",
           "The method is the strongest accepted link touching the record. Rule confidences are stated values from "
           "`config/settings.yaml`; Splink confidences are match probabilities.", ""]
    md += [table(q("""SELECT match_method, count(*), round(min(match_confidence), 4), round(avg(match_confidence), 4)
                      FROM gold.customer_xref GROUP BY 1 ORDER BY 2 DESC"""), ["method", "records", "min confidence", "mean confidence"]), ""]
    md += ["CRM records per person:", "",
           table(q("""SELECT n, count(*) FROM (SELECT golden_customer_id, count(*) FILTER (WHERE source_system = 'crm') n
                      FROM gold.customer_xref GROUP BY 1) GROUP BY 1 ORDER BY 1"""), ["CRM records", "people"]), ""]

    md += ["## 3. Links proposed, accepted and refused", ""]
    md += [table(q("SELECT method, status, count(*) FROM identity.rule_links GROUP BY ALL ORDER BY 1, 2"),
                 ["exact rule", "status", "pairs"]), ""]
    md += [table(q("SELECT route, count(*), round(min(match_probability), 4) FROM identity.splink_pairs GROUP BY 1 ORDER BY 1"),
                 ["Splink route", "pairs", "min probability"]), "",
           f"Routing: >= {s['link_threshold']} link, {s['review_threshold']}-{s['link_threshold']} grey zone (LLM, then a person), "
           f"< {s['review_threshold']} not stored (kept separate).", ""]
    md += [table(q("SELECT status, count(*) FROM identity.llm_verdicts GROUP BY 1 ORDER BY 1") or [("none", 0)],
                 ["LLM second opinion", "pairs"]), ""]
    md += [table(q("SELECT method, count(*) FROM identity.accepted_links GROUP BY 1 ORDER BY 2 DESC"), ["accepted link method", "links"]), ""]

    md += ["## 4. Precision against independent evidence", "",
           "Collections cases list the accounts they cover under a CRM ID. For each account the check asks: is the account "
           "holder's golden ID the golden ID of the case's CRM record? Cases whose CRM ID does not exist are left out.", ""]
    con.execute(EVIDENCE_SQL)
    rows = q("""SELECT split_part(e.acct_node, '|', 1), x.match_method, count(*),
                       count(*) FILTER (WHERE e.acct_golden = e.case_golden),
                       count(*) FILTER (WHERE e.acct_golden <> e.case_golden AND EXISTS (
                           SELECT 1 FROM gold.customer_xref c WHERE c.golden_customer_id = e.acct_golden AND c.source_system = 'crm'
                           AND levenshtein(c.source_key, e.case_crm) = 1)),
                       count(*) FILTER (WHERE e.acct_golden <> e.case_golden)
                FROM case_evidence e JOIN gold.customer_xref x ON x.node_id = e.acct_node
                WHERE e.case_golden IS NOT NULL GROUP BY ALL ORDER BY 1, 2""")
    md += [table([(*r[:4], r[3] / r[2] if r[2] else 0.0, r[4], r[5] - r[4], (r[3] + r[4]) / r[2] if r[2] else 0.0) for r in rows],
                 ["account source", "method", "pairs", "same person", "agreement", "case CRM ID one character off",
                  "other disagreements", "agreement allowing for case typos"]), ""]
    tot = one("""SELECT count(*), count(*) FILTER (WHERE acct_golden = case_golden) FROM case_evidence WHERE case_golden IS NOT NULL""")
    md += [f"Overall: {tot[1]:,} of {tot[0]:,} account-case pairs agree ({100 * tot[1] / max(tot[0], 1):.2f}%). "
           "Where they disagree, the case's own fields disagree: its accounts belong to one customer and its CRM ID, one "
           "character away from that customer's real ID, names a different real customer (almost certainly a typo). "
           "The two customers are never merged. `gold.case_customer` keeps both readings, resolves the case to the "
           "account holder and sets `case_customer_mismatch`; case safety flags reach both people."""]

    md += ["## 5. Contract rules for identity", ""]
    checks = [
        ("Q1 golden_customer_id unique and not null in c360_customer",
         "SELECT count(*) - count(DISTINCT golden_customer_id) + count(*) FILTER (WHERE golden_customer_id IS NULL) FROM gold.c360_customer"),
        ("Q2 every source record in customer_xref exactly once",
         "SELECT (SELECT count(*) FROM identity.nodes) - (SELECT count(DISTINCT node_id) FROM gold.customer_xref) "
         "+ (SELECT count(*) - count(DISTINCT node_id) FROM gold.customer_xref)"),
        ("Q3 no accepted link below 0.80; 0.80-0.95 only via LLM agreement or a person",
         "SELECT count(*) FROM identity.accepted_links WHERE confidence < 0.80 OR (confidence < 0.95 AND method NOT IN ('llm_confirmed', 'human'))"),
        ("Cluster: no person with two national ID hashes",
         "SELECT count(*) FROM (SELECT x.golden_customer_id FROM gold.customer_xref x JOIN identity.nodes n USING (node_id) "
         "GROUP BY 1 HAVING count(DISTINCT n.national_id_hash) > 1)"),
        (f"Cluster: no person with more than {s['max_crm_per_cluster']} CRM records",
         f"SELECT count(*) FROM (SELECT golden_customer_id FROM gold.customer_xref WHERE source_system = 'crm' GROUP BY 1 "
         f"HAVING count(*) > {s['max_crm_per_cluster']})"),
        ("Joint holders / co-borrowers never one person",
         "SELECT count(*) FROM identity.relationship_pairs r JOIN gold.customer_xref a ON a.node_id = r.node_a "
         "JOIN gold.customer_xref b ON b.node_id = r.node_b WHERE a.golden_customer_id = b.golden_customer_id"),
    ]
    md += [table([(name, one(sql)[0], "pass" if one(sql)[0] == 0 else "FAIL") for name, sql in checks],
                 ["rule", "violations", "result"]), ""]

    md += ["## 6. Open review items", "",
           table(q("SELECT reason, count(*) FROM gold.identity_review_queue GROUP BY 1 ORDER BY 2 DESC"), ["reason", "pairs"]), "",
           "Decisions go in `data/review/identity_decisions.csv` (`node_a, node_b, decision, reviewer, decided_ts, "
           "evidence_key, note`; decision `match | no_match | unresolved`) and are re-applied on every run. Copy "
           "`evidence_key` from the queue so a decision lapses if either record changes.", ""]
    md += ["## 7. Relationships (never merged)", "",
           table(q("SELECT relationship_type, count(*) FROM gold.customer_relationship GROUP BY 1 ORDER BY 1"), ["type", "pairs"]), ""]
    return "\n".join(md)


def main() -> None:
    con = connect()
    text = build(con)
    con.close()
    REPORT.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
