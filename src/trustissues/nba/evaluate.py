"""Model evaluation on the holdout, and the incumbent ptp_break baseline.

    python -m trustissues.nba.evaluate        # scores the incumbent, writes reports/model_evaluation.md

`evaluate(scores, labels)` is shared with nba/train.py so the incumbent and our model are measured
the same way: AUC, calibration (reliability table + Brier score), and the share of broken promises
caught in the riskiest 20%.
"""
from __future__ import annotations

import re

import numpy as np
from sklearn.metrics import brier_score_loss, roc_auc_score

from trustissues.common import config
from trustissues.common.db import connect
from trustissues.features import sources
from trustissues.features.build_training_set import SPINE_FILE

REPORT = config.REPO_ROOT / "reports" / "model_evaluation.md"
TOP_SHARE = 0.20


def evaluate(scores, labels, bins: int = 10) -> dict:
    """scores: predicted probability of breaking; labels: 1 = broken / partially kept."""
    s = np.asarray(scores, dtype=float)
    y = np.asarray(labels, dtype=int)
    order = np.argsort(-s, kind="stable")
    k = int(np.ceil(TOP_SHARE * len(s)))
    edges = np.unique(np.quantile(s, np.linspace(0, 1, bins + 1)))
    idx = np.clip(np.searchsorted(edges, s, side="right") - 1, 0, len(edges) - 2)
    reliability = [
        {"bin": int(b), "n": int((idx == b).sum()), "mean_score": float(s[idx == b].mean()),
         "broken_rate": float(y[idx == b].mean())}
        for b in range(len(edges) - 1) if (idx == b).any()
    ]
    ece = sum(r["n"] * abs(r["mean_score"] - r["broken_rate"]) for r in reliability) / len(s)
    return {
        "n": int(len(s)),
        "broken_rate": float(y.mean()),
        "auc": float(roc_auc_score(y, s)),
        "brier": float(brier_score_loss(y, np.clip(s, 0, 1))),
        "ece": float(ece),
        "mean_score": float(s.mean()),
        "top20_capture": float(y[order[:k]].sum() / max(y.sum(), 1)),
        "top20_broken_rate": float(y[order[:k]].mean()),
        "reliability": reliability,
    }


def format_result(name: str, r: dict) -> str:
    lines = [
        f"| Metric | {name} |", "|---|---|",
        f"| Promises scored | {r['n']:,} |",
        f"| Broken rate (actual) | {r['broken_rate']:.1%} |",
        f"| Mean score | {r['mean_score']:.3f} |",
        f"| AUC | **{r['auc']:.4f}** |",
        f"| Brier score (lower is better) | {r['brier']:.4f} |",
        f"| Expected calibration error | {r['ece']:.4f} |",
        f"| Broken promises caught in riskiest 20% | **{r['top20_capture']:.1%}** |",
        f"| Broken rate inside riskiest 20% | {r['top20_broken_rate']:.1%} |",
        "", "Reliability (score deciles):", "",
        "| Decile | Promises | Mean score | Actual broken rate |", "|---|---|---|---|",
    ]
    lines += [f"| {b['bin'] + 1} | {b['n']:,} | {b['mean_score']:.3f} | {b['broken_rate']:.3f} |"
              for b in r["reliability"]]
    return "\n".join(lines)


def comparison_table(results: dict[str, dict]) -> str:
    names = list(results)
    rows = [("AUC", "auc", "{:.4f}"), ("Brier score", "brier", "{:.4f}"), ("Calibration error", "ece", "{:.4f}"),
            ("Caught in riskiest 20%", "top20_capture", "{:.1%}"), ("Promises", "n", "{:,}")]
    out = ["| Metric | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    out += [f"| {label} | " + " | ".join(fmt.format(results[n][key]) for n in names) + " |" for label, key, fmt in rows]
    return "\n".join(out)


def write_section(name: str, body: str) -> None:
    """Replace (or append) one named section of reports/model_evaluation.md, keeping the others."""
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    text = REPORT.read_text(encoding="utf-8") if REPORT.exists() else (
        "# Model evaluation: promise-to-pay break risk\n\n"
        "Generated by `nba/evaluate.py`, `nba/train.py` and `nba/actions.py`. Holdout = resolved promises the "
        "incumbent `ptp_break` model scored (see `features/build_training_set.py`). Label: broken or partially "
        "kept = 1, kept = 0.\n")
    block = f"<!-- section:{name} -->\n{body.strip()}\n<!-- /section:{name} -->"
    pattern = re.compile(rf"<!-- section:{re.escape(name)} -->.*?<!-- /section:{re.escape(name)} -->", re.S)
    text = pattern.sub(lambda _: block, text) if pattern.search(text) else text.rstrip() + "\n\n" + block + "\n"
    REPORT.write_text(text, encoding="utf-8")


def holdout_labels(con):
    path = (config.p3_dir() / SPINE_FILE).as_posix()
    return con.sql(f"SELECT ptp_id, event_ts, label FROM read_parquet('{path}') WHERE split = 'holdout'")


def incumbent_holdout_scores(con) -> tuple[dict, list]:
    """First incumbent score dated on or after the promise was created, per holdout promise."""
    sources.register(con)
    labels = holdout_labels(con)
    con.register("holdout_labels", labels)
    stats = con.execute("""
        WITH c AS (
            SELECT h.ptp_id, count(s.ptp_id) AS n_scores,
                   count(s.ptp_id) FILTER (WHERE s.score_date >= CAST(h.event_ts AS DATE)) AS n_after
            FROM holdout_labels h LEFT JOIN src_incumbent_ptp_scores s USING (ptp_id) GROUP BY 1)
        SELECT count(*) FILTER (WHERE n_scores > 1), count(*) FILTER (WHERE n_after = 0) FROM c""").fetchone()
    rows = con.execute("""
        SELECT h.ptp_id, h.label, arg_min(s.score, s.score_ts) AS score, arg_min(s.model_version, s.score_ts)
        FROM holdout_labels h JOIN src_incumbent_ptp_scores s
          ON s.ptp_id = h.ptp_id AND s.score_date >= CAST(h.event_ts AS DATE)
        GROUP BY h.ptp_id, h.label ORDER BY h.ptp_id""").fetchall()
    return {"multiple_scores": stats[0], "no_score_on_or_after": stats[1]}, rows


def main() -> int:
    con = connect(read_only=True)
    stats, rows = incumbent_holdout_scores(con)
    r = evaluate([x[2] for x in rows], [x[1] for x in rows])
    versions = ", ".join(sorted({f"`{x[3]}`" for x in rows}))
    print(f"holdout promises with several incumbent scores: {stats['multiple_scores']:,} (first score on/after "
          f"creation used); with no score on/after creation: {stats['no_score_on_or_after']:,} (dropped)")
    print(f"incumbent ptp_break: AUC {r['auc']:.4f}, Brier {r['brier']:.4f}, ECE {r['ece']:.4f}, "
          f"top-20% capture {r['top20_capture']:.1%} on {r['n']:,} promises")
    write_section("incumbent", f"""
## Incumbent `ptp_break` (the bar to beat)

The bank's model as scored in `model_scores` (version {versions}). For each
holdout promise the first score dated on or after the promise was created is used. Promises with several
scores: {stats['multiple_scores']:,}. Promises with no score on or after creation (dropped):
{stats['no_score_on_or_after']:,}.

{format_result("Incumbent ptp_break", r)}
""")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
